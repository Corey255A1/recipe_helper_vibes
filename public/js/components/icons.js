const Theme = {
  STORAGE_KEY: 'recipe_helper_theme',

  get() {
    const saved = localStorage.getItem(this.STORAGE_KEY);
    return saved === 'light' ? 'light' : 'dark';
  },

  apply(mode) {
    const theme = mode === 'light' ? 'light' : 'dark';
    document.documentElement.setAttribute('data-theme', theme);
    localStorage.setItem(this.STORAGE_KEY, theme);

    const meta = document.querySelector('meta[name="theme-color"]');
    if (meta) {
      meta.setAttribute('content', theme === 'light' ? '#faf7f2' : '#121110');
    }
    this.updateToggleUI(theme);
  },

  toggle() {
    const next = this.get() === 'light' ? 'dark' : 'light';
    this.apply(next);
    return next;
  },

  updateToggleUI(theme) {
    const headerBtn = document.getElementById('theme-toggle-btn');
    if (headerBtn) {
      headerBtn.innerHTML = theme === 'light' ? Icons.render('moon', 17) : Icons.render('sun', 17);
      headerBtn.title = theme === 'light' ? 'Switch to Dark Mode' : 'Switch to Light Mode';
      headerBtn.setAttribute('aria-label', headerBtn.title);
    }
    const settingsSelect = document.getElementById('ctx-theme-select');
    if (settingsSelect) {
      settingsSelect.value = theme;
    }
  },

  init() {
    this.apply(this.get());
  }
};

window.Icons = Icons;
window.Theme = Theme;
